/** מקדם של x: 1 → x, ‏-1 → -x */
const cx = (k: number, v = 'x') => (k === 1 ? v : k === -1 ? `-${v}` : `${k}${v}`);
/** איבר עם סימן לפניו, לשרשור: + 3x, - x */
const term = (k: number, v = 'x') => (k < 0 ? `- ${cx(-k, v)}` : `+ ${cx(k, v)}`);
const nz = (lo: number, hi: number) => {
  let v = ri(lo, hi);
  while (v === 0) v = ri(lo, hi);
  return v;
};
const COEF = 'מקדם x';
const FREE = 'מספר חופשי';

