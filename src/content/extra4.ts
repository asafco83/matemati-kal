const frac = (n: number, d: number) => {
  const g = gcd(Math.abs(n), Math.abs(d));
  const [a, b] = [n / g, d / g];
  return b === 1 ? `${a}` : L`${a < 0 ? '-' : ''}\frac{${Math.abs(a)}}{${b}}`;
};
