const parab = (r1: number, r2: number, up = true): [number, number][] => {
  const pts: [number, number][] = [];
  for (let x = Math.min(r1, r2) - 2; x <= Math.max(r1, r2) + 2; x += 0.25) pts.push([x, (up ? 1 : -1) * (x - r1) * (x - r2)]);
  return pts;
};

