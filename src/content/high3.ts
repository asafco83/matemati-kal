/** תחום אפשרי: x, y ≥ 0, ‏x + y ≤ s, ‏x + ky ≤ t. הקודקודים שלמים */
function lpRegion() {
  const k = pick([2, 3]);
  const p = k * ri(1, 2);
  const q = ri(1, 4);
  const s = p + q;
  const t = p + k * q;
  const yTop = t / k;
  const V: [number, number][] = [[0, 0], [s, 0], [p, q], [0, yTop]];
  const range = Math.max(s, yTop) + 1;
  const ky = k === 1 ? 'y' : `${k}y`;
  const figure = {
    type: 'graph' as const,
    q1: true,
    range,
    lines: [{ m: -1, b: s }, { m: -1 / k, b: yTop }],
    region: V,
    points: V,
    pointLabels: ['O', 'A', 'B', 'C'],
  };
  return { k, p, q, s, t, yTop, V, ky, figure };
}

