const times = (k: number) => (k === 0 ? 'אפס פעמים' : k === 1 ? 'פעם אחת' : k === 2 ? 'פעמיים' : `${k} פעמים`);

/**
 * הפתרון של חילוק ארוך, כמו שכותבים אותו במחברת: בכל צעד רואים את החילוק
 * עד אותו שלב, ומה שנוסף עכשיו מסומן בצהוב.
 */
function longDivSteps(n: number, d: number): { steps: Step[]; q: number; r: number } {
  const ds = digitsOf(n);
  const steps: Step[] = [
    { figure: { type: 'longdiv', n, d, upto: 0 }, caption: `כותבים את המחולק ${n}, מימינו קו ואת המחלק ${d}. מעל ${n} מותחים קו: שם תיכתב המנה.` },
  ];
  let cur = 0;
  let q = '';
  ds.forEach((dig, i) => {
    cur = cur * 10 + dig;
    const k = Math.floor(cur / d);
    const left = cur - k * d;
    const intro = i === 0 ? 'מתחילים מהספרה השמאלית של המחולק.' : '';
    const end = i < ds.length - 1 ? `מורידים את הספרה הבאה, ${ds[i + 1]}, ומקבלים ${left * 10 + ds[i + 1]}.` : `אין עוד ספרות להוריד, אז ${left} היא השארית.`;
    steps.push({
      figure: { type: 'longdiv', n, d, upto: 3 + 3 * i, from: 1 + 3 * i },
      caption: `${intro} כמה פעמים ${d} נכנס ב-${cur}? ${times(k)}, אז כותבים ${k} במנה. ${k} כפול ${d} הם ${k * d}: כותבים מתחת ומחסרים, ונשאר ${left}. ${end}`.trim(),
    });
    q += String(k);
    cur = left;
  });
  return { steps, q: Number(q), r: cur };
}

