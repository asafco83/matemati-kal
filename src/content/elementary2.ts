/**
 * כפל במאונך כמו במחברת: בכל צעד רואים את התרגיל עד אותו שלב, ומה שנוסף מסומן בצהוב.
 * b חד-ספרתי או דו-ספרתי.
 */
function longMultSteps(a: number, b: number): Step[] {
  const da = digitsOf(a).reverse();
  const L = da.length;
  const steps: Step[] = [
    { figure: { type: 'longmul', a, b, upto: 0 }, caption: `כותבים את ${a}, ומתחתיו את ${b} כך שהאחדות מתחת לאחדות. משמאל ל-${b} כותבים ×, ומתחת מותחים קו.` },
  ];
  const row = (m: number, stage0: number, place: string) => {
    let carry = 0;
    da.forEach((d, i) => {
      const v = d * m + carry;
      const lastDigit = i === L - 1;
      const plus = carry ? `, ועוד ${carry} שהעברנו` : '';
      const write = lastDigit ? `כותבים ${v}.` : v >= 10 ? `כותבים ${v % 10}, ואת ה-${Math.floor(v / 10)} מעבירים: כותבים אותו קטן מעל העמודה הבאה.` : `כותבים ${v}.`;
      steps.push({
        figure: { type: 'longmul', a, b, upto: stage0 + i, from: stage0 + i },
        caption: `${i === 0 ? place : ''}${m} כפול ${d} (${PLACES[i]} של ${a}) הם ${d * m}${plus}: ${v}. ${write}`,
      });
      carry = lastDigit ? 0 : Math.floor(v / 10);
    });
  };
  if (b < 10) {
    row(b, 1, '');
    return steps;
  }
  const u = b % 10;
  const t = Math.floor(b / 10);
  row(u, 1, `שורה ראשונה, כופלים באחדות של ${b}: `);
  steps.push({
    figure: { type: 'longmul', a, b, upto: L + 1, from: L + 1 },
    caption: `שורה שנייה: כופלים בעשרות של ${b}, כלומר ב-${t * 10}. לכן כותבים קודם 0 בעמודת האחדות, וממשיכים משמאלו.`,
  });
  row(t, L + 2, '');
  steps.push({
    figure: { type: 'longmul', a, b, upto: 2 * L + 2, from: 2 * L + 2 },
    caption: `מותחים קו, ומחברים את שתי השורות: ${a * u} ועוד ${a * t * 10} הם ${a * b}.`,
  });
  return steps;
}

